#!/usr/bin/env python3
"""Render banner, og and the deterministic synthetic demo with Chrome and FFmpeg.

Banner is 2560x640; og is 1280x640 and under 1,000,000 bytes. The demo samples
assets/demo.html at t=i/20 for 16 seconds: 320 PNGs at 1920x1080, a 960x540
10-fps looping GIF, a 20-fps libx264/yuv420p MP4 and the t=5.6-second PNG poster.
GIF/MP4 have 3 MiB caps; the GIF targets 1.5 MiB with a 256-color full palette,
Bayer-3 dithering, optional diff/Bayer-5 fallback and optional gifsicle -O3.
Frame workers reuse separate temporary Chrome profiles, with 60-second calls.
Webfonts need network access; no live Tern session is captured. --chrome/CHROME
and --ffmpeg/FFMPEG override normal tool discovery; demo also needs ffprobe.
All requested outputs are staged and validated before publication, with the demo
manifest written last. --check compares regenerated bytes without publishing;
it is a same-machine check, not a CI check. --keep-frames preserves demo PNGs.
"""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import tempfile
import threading
from typing import Iterable

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
TARGETS = {
    "banner": (1280, 320, 2),
    "og": (1280, 640, 1),
}
MEDIA = ROOT / "docs/media"
DEMO = (960, 540, 2)
FPS = 20
DURATION_S = 16.0
GIF_FPS = 10
GIF_WIDTH = 960
POSTER_T = 5.6  # waiting_for_input, at the amber pulse's peak (3.6 s + 1.25 periods of 1.6 s)
DEMO_SOURCES = ("assets/brand.css", "assets/demo.html", "assets/logo.svg")
MEDIA_FILES = (
    "tern-sidepulse-demo.gif",
    "tern-sidepulse-demo.mp4",
    "tern-sidepulse-demo-poster.png",
    "README.md",
    "manifest.json",
)


def chrome_path(explicit: str | None) -> str:
    candidates = [
        explicit,
        os.environ.get("CHROME"),
        shutil.which("google-chrome"),
        shutil.which("chromium"),
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).expanduser().is_file():
            return str(Path(candidate).expanduser())
    raise SystemExit("Chrome/Chromium not found; pass --chrome or set CHROME")


def ffmpeg_path(explicit: str | None) -> str:
    candidates = [
        explicit,
        os.environ.get("FFMPEG"),
        shutil.which("ffmpeg"),
        str(Path.home() / ".local/bin/ffmpeg"),
        "/opt/homebrew/bin/ffmpeg",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).expanduser().is_file():
            return str(Path(candidate).expanduser())
    raise SystemExit("FFmpeg not found; pass --ffmpeg or set FFMPEG")


def ffprobe_path(ffmpeg: str) -> str:
    candidates = [
        str(Path(ffmpeg).with_name("ffprobe")),
        shutil.which("ffprobe"),
        str(Path.home() / ".local/bin/ffprobe"),
        "/opt/homebrew/bin/ffprobe",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return candidate
    raise SystemExit("ffprobe not found; install it alongside FFmpeg or on PATH")


def png_dimensions(path: Path) -> tuple[int, int]:
    with path.open("rb") as stream:
        if stream.read(8) != b"\x89PNG\r\n\x1a\n":
            raise RuntimeError(f"not a PNG: {path}")
        length = struct.unpack(">I", stream.read(4))[0]
        kind = stream.read(4)
        if kind != b"IHDR" or length < 8:
            raise RuntimeError(f"missing PNG IHDR: {path}")
        return struct.unpack(">II", stream.read(8))


def gif_dimensions(path: Path) -> tuple[int, int]:
    with path.open("rb") as stream:
        if stream.read(6) != b"GIF89a":
            raise RuntimeError(f"not a GIF89a: {path}")
        return struct.unpack("<HH", stream.read(4))


def source_digest(paths: Iterable[str | Path]) -> str:
    digest = hashlib.sha256()
    sources = []
    for path in paths:
        relative = Path(path)
        if relative.is_absolute():
            relative = relative.relative_to(ROOT)
        sources.append((relative.as_posix(), ROOT / relative))
    for name, path in sorted(sources):
        digest.update(name.encode("utf-8") + b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def command_output(command: list[str], timeout: int = 60) -> str:
    result = subprocess.run(command, check=True, capture_output=True, text=True, timeout=timeout)
    return result.stdout.strip()


def chrome_flags(chrome: str, viewport: tuple[int, int, int], profile: Path) -> list[str]:
    width, height, scale = viewport
    return [
        chrome,
        "--headless=new",
        "--hide-scrollbars",
        "--disable-gpu",
        "--force-color-profile=srgb",
        f"--force-device-scale-factor={scale}",
        f"--window-size={width},{height}",
        "--virtual-time-budget=5000",
        "--no-first-run",
        "--no-default-browser-check",
        f"--user-data-dir={profile}",
    ]


def preflight_fonts(chrome: str, stage: Path) -> None:
    command = chrome_flags(chrome, DEMO, stage / "font-profile")
    command += ["--dump-dom", (ASSETS / "demo.html").as_uri() + "?probe=fonts"]
    if 'data-fonts="ok"' not in command_output(command):
        raise RuntimeError("webfonts unavailable; the render needs network access")


def screenshot(
    chrome: str,
    source: Path,
    output: Path,
    viewport: tuple[int, int, int],
    profile: Path,
    t: float = 0.0,
) -> tuple[int, int]:
    command = chrome_flags(chrome, viewport, profile)
    command += [f"--screenshot={output}", source.as_uri() + f"?t={t:.3f}"]
    subprocess.run(command, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, timeout=60)
    width, height, scale = viewport
    expected = (width * scale, height * scale)
    observed = png_dimensions(output)
    if observed != expected:
        raise RuntimeError(f"{output.name}: expected {expected}, observed {observed}")
    return observed


def render(chrome: str, name: str, stage: Path) -> Path:
    output = stage / f"{name}.png"
    observed = screenshot(chrome, ASSETS / f"{name}.html", output, TARGETS[name], stage / "artwork-profile")
    if name == "og" and output.stat().st_size >= 1_000_000:
        raise RuntimeError("og.png must be smaller than 1,000,000 bytes")
    print(f"{name}: {observed[0]}x{observed[1]}", flush=True)
    return output


def render_frames(chrome: str, stage: Path, jobs: int, keep_frames: Path | None) -> Path:
    frames = stage / "frames"
    frames.mkdir()
    worker = threading.local()

    def initialize() -> None:
        worker.profile = stage / f"frame-profile-{threading.get_ident()}"

    def capture(index: int) -> None:
        screenshot(
            chrome,
            ASSETS / "demo.html",
            frames / f"frame_{index:04d}.png",
            DEMO,
            worker.profile,
            index / FPS,
        )

    with ThreadPoolExecutor(max_workers=jobs, initializer=initialize) as executor:
        for _ in executor.map(capture, range(int(DURATION_S * FPS))):
            pass
    if keep_frames is not None:
        keep_frames.mkdir(parents=True, exist_ok=True)
        shutil.copytree(frames, keep_frames, dirs_exist_ok=True)
    return frames


def gif_filter(stats_mode: str, bayer_scale: int) -> str:
    return (
        f"fps={GIF_FPS},scale={GIF_WIDTH}:-1:flags=lanczos,split[a][b];"
        f"[a]palettegen=max_colors=256:stats_mode={stats_mode}[p];"
        f"[b][p]paletteuse=dither=bayer:bayer_scale={bayer_scale}:diff_mode=rectangle"
    )


def encode_gif(ffmpeg: str, frames: Path, stage: Path) -> tuple[Path, dict]:
    gifsicle = Path("/opt/homebrew/bin/gifsicle")
    best = None
    chosen = None
    for stats_mode, bayer_scale in (("full", 3), ("diff", 3), ("diff", 5)):
        output = stage / f"demo-{stats_mode}-{bayer_scale}.gif"
        filtergraph = gif_filter(stats_mode, bayer_scale)
        command_output(
            [
                ffmpeg, "-hide_banner", "-loglevel", "error", "-y",
                "-framerate", str(FPS), "-i", str(frames / "frame_%04d.png"),
                "-filter_complex", filtergraph,
                "-loop", "0", "-map_metadata", "-1", "-fflags", "+bitexact", "-flags:v", "+bitexact",
                str(output),
            ],
            timeout=300,
        )
        if gifsicle.is_file():
            optimized = output.with_name(output.stem + "-optimized.gif")
            # Keep the prescribed 160 samples even when adjacent frames are identical.
            command_output(
                [str(gifsicle), "-O3", "-Okeep-empty", "--output", str(optimized), str(output)],
                timeout=300,
            )
            output = optimized
        if gif_dimensions(output) != (GIF_WIDTH, 540):
            raise RuntimeError(f"{output.name}: expected GIF dimensions 960x540")
        if best is None or output.stat().st_size < best.stat().st_size:
            best = output
            chosen = {
                "fps": GIF_FPS,
                "frames": int(DURATION_S * GIF_FPS),
                "width": GIF_WIDTH,
                "max_colors": 256,
                "stats_mode": stats_mode,
                "dither": "bayer",
                "bayer_scale": bayer_scale,
                "diff_mode": "rectangle",
                "loop": 0,
                "bitexact": True,
                "gifsicle_o3": gifsicle.is_file(),
                "gifsicle_keep_empty": gifsicle.is_file(),
                "filtergraph": filtergraph,
            }
        if best.stat().st_size <= 1.5 * 1024 * 1024:
            break
    if best is None or chosen is None or best.stat().st_size > 3 * 1024 * 1024:
        raise RuntimeError("demo GIF exceeds the 3 MiB hard cap")
    destination = stage / MEDIA_FILES[0]
    os.replace(best, destination)
    return destination, chosen


def probe_video(ffprobe: str, path: Path) -> dict:
    result = json.loads(command_output([
        ffprobe, "-v", "error", "-select_streams", "v:0",
        "-show_entries", "stream=width,height,nb_frames", "-of", "json", str(path),
    ]))
    streams = result.get("streams", [])
    expected = (DEMO[0] * DEMO[2], DEMO[1] * DEMO[2], int(DURATION_S * FPS))
    observed = None
    if len(streams) == 1:
        stream = streams[0]
        observed = (stream.get("width"), stream.get("height"), int(stream.get("nb_frames", -1)))
    if observed != expected:
        raise RuntimeError(f"{path.name}: expected width/height/frames {expected}, observed {observed}")
    return streams[0]


def output_record(path: Path, dimensions: tuple[int, int]) -> dict:
    return {
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "bytes": path.stat().st_size,
        "width": dimensions[0],
        "height": dimensions[1],
    }


def render_demo(
    chrome: str, ffmpeg: str, ffprobe: str, tools: dict, stage: Path, jobs: int, keep_frames: Path | None,
) -> dict[Path, Path]:
    digest = source_digest(DEMO_SOURCES)
    frames = render_frames(chrome, stage, jobs, keep_frames)
    mp4 = stage / MEDIA_FILES[1]
    command_output(
        [
            ffmpeg, "-hide_banner", "-loglevel", "error", "-y",
            "-framerate", str(FPS), "-i", str(frames / "frame_%04d.png"),
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "20", "-preset", "slow",
            "-tune", "animation", "-r", str(FPS), "-an", "-movflags", "+faststart",
            "-map_metadata", "-1", "-fflags", "+bitexact", "-flags:v", "+bitexact", str(mp4),
        ],
        timeout=300,
    )
    probe_video(ffprobe, mp4)
    if mp4.stat().st_size > 3 * 1024 * 1024:
        raise RuntimeError("demo MP4 exceeds the 3 MiB hard cap")
    gif, gif_params = encode_gif(ffmpeg, frames, stage)
    poster = stage / MEDIA_FILES[2]
    shutil.copyfile(frames / f"frame_{int(POSTER_T * FPS):04d}.png", poster)
    dimensions = (DEMO[0] * DEMO[2], DEMO[1] * DEMO[2])
    if png_dimensions(poster) != dimensions:
        raise RuntimeError("demo poster dimensions do not match the frame canvas")
    if gif_params["gifsicle_o3"]:
        tools["gifsicle"] = command_output(["/opt/homebrew/bin/gifsicle", "--version"]).splitlines()[0]
    manifest = {
        "schema": 1,
        "source": {"files": sorted(DEMO_SOURCES), "sha256": digest},
        "tools": tools,
        "params": {
            "canvas": list(DEMO[:2]),
            "device_scale_factor": DEMO[2],
            "fps": FPS,
            "frames": int(DURATION_S * FPS),
            "duration_s": DURATION_S,
            "poster_t": POSTER_T,
            "frame_time": "i / FPS",
            "color_profile": "srgb",
            "virtual_time_budget_ms": 5000,
            "gif": gif_params,
            "mp4": {
                "codec": "libx264", "pixel_format": "yuv420p", "crf": 20, "preset": "slow",
                "tune": "animation", "fps": FPS, "audio": False, "faststart": True,
                "map_metadata": -1, "bitexact": True,
            },
        },
        "outputs": {
            gif.name: output_record(gif, gif_dimensions(gif)),
            mp4.name: output_record(mp4, dimensions),
            poster.name: output_record(poster, dimensions),
        },
    }
    manifest_path = stage / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    print(f"demo: {int(DURATION_S * FPS)} frames, {DURATION_S:g}s, {FPS} fps", flush=True)
    return {MEDIA / path.name: path for path in (gif, mp4, poster, manifest_path)}


def positive_int(value: str) -> int:
    number = int(value)
    if number < 1:
        raise argparse.ArgumentTypeError("must be at least 1")
    return number


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("names", nargs="*", metavar="{banner,og,demo}")
    parser.add_argument("--chrome")
    parser.add_argument("--ffmpeg")
    parser.add_argument("--jobs", type=positive_int, default=min(4, os.cpu_count() or 1))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--keep-frames", type=Path)
    args = parser.parse_args()
    names = list(dict.fromkeys(args.names or [*TARGETS, "demo"]))
    unknown = set(names) - {*TARGETS, "demo"}
    if unknown:
        parser.error("unknown targets: " + ", ".join(sorted(unknown)))
    chrome = chrome_path(args.chrome)
    tools = {"chrome": command_output([chrome, "--version"])}
    ffmpeg = ffprobe = None
    if "demo" in names:
        ffmpeg = ffmpeg_path(args.ffmpeg)
        ffprobe = ffprobe_path(ffmpeg)
        encoders = command_output([ffmpeg, "-hide_banner", "-encoders"])
        if not any(line.split()[1:2] == ["libx264"] for line in encoders.splitlines()):
            raise RuntimeError("FFmpeg libx264 encoder unavailable")
        tools["ffmpeg"] = command_output([ffmpeg, "-version"]).splitlines()[0]
        tools["ffprobe"] = command_output([ffprobe, "-version"]).splitlines()[0]
    with tempfile.TemporaryDirectory(prefix="tern-sidepulse-render-") as directory:
        stage = Path(directory)
        preflight_fonts(chrome, stage)
        staged = {}
        for name in names:
            if name == "demo":
                staged.update(render_demo(chrome, ffmpeg, ffprobe, tools, stage, args.jobs, args.keep_frames))
            else:
                staged[ASSETS / f"{name}.png"] = render(chrome, name, stage)
        if args.check:
            stale = [destination for destination, output in staged.items()
                     if not destination.is_file() or destination.read_bytes() != output.read_bytes()]
            for destination in stale:
                print(f"stale: {destination.relative_to(ROOT).as_posix()}", file=sys.stderr)
            return 1 if stale else 0
        manifest = MEDIA / "manifest.json"
        for destination, output in staged.items():
            if destination != manifest:
                destination.parent.mkdir(parents=True, exist_ok=True)
                os.replace(output, destination)
        if manifest in staged:
            MEDIA.mkdir(parents=True, exist_ok=True)
            os.replace(staged[manifest], manifest)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (RuntimeError, OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"render_assets: {error}", file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError) and error.stderr:
            detail = error.stderr.decode("utf-8", errors="replace") if isinstance(error.stderr, bytes) else error.stderr
            print(detail, file=sys.stderr)
        raise SystemExit(1)
